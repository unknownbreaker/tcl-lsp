"""Build <results>/SUMMARY.md from <results>/<repo>.json.
Usage: python3 -I summarize.py --results DIR"""
import argparse
import glob
import json
import os
from collections import Counter, defaultdict

ap = argparse.ArgumentParser(description='Build SUMMARY.md from harness results.')
ap.add_argument('--results', required=True, help='directory holding <repo>.json')
RES = os.path.abspath(ap.parse_args().results)
R = {}
for f in sorted(glob.glob(os.path.join(RES, '*.json'))):
    d = json.load(open(f))
    R[d['repo']] = d
L = []
w = L.append


def norm_tag(t):
    for p in ('ns:', 'proc:', 'method:', 'class:', 'oo:', 'snit:', 'proclike:'):
        if t.startswith(p):
            return p.rstrip(':') + '-body'
    if t.startswith('data:'):
        return 'data-brace'
    if t.startswith('unknown-arg:'):
        return 'unknown-nontrailing-brace'
    return t


def ex(r, keys):
    return ' '.join('%s=%s' % (k, json.dumps(r.get(k))[:160]) for k in keys if r.get(k) not in (None, [], ''))


def table(rows, hdr):
    w('| ' + ' | '.join(hdr) + ' |')
    w('|' + '---|' * len(hdr))
    for r in rows:
        w('| ' + ' | '.join(str(x) for x in r) + ' |')
    w('')


w('# tcl-lsp Phase 1 probe harness: SUMMARY')
w('')
w('Server `main@26f8ab2`; corpus shallow clones; generated by `summarize.py` from `results/<repo>.json`. '
  'All classes are *candidates* from an independent, lenient oracle (see README.md for caveats).')
w('')
w('## Cross-repo table')
w('')
rows = []
for n, d in R.items():
    cc, oc, vc = d['call_counts'], d['obj_counts'], d['var_counts']
    dm_models = sum(1 for m in d['def_misses'] if m['models'])
    slow = d['slowest_files'][0] if d['slowest_files'] else {}
    long = [f for f in d['files_flagged'] if f.get('retry_long')]
    slow_s = '%s %s %.0fms' % (slow.get('file'), slow.get('method'), slow.get('max_ms', 0))
    if long:
        slow_s += ' (retry: ' + ', '.join('%s %.0fs' % (k, v['ms'] / 1000) for k, v in long[0]['retry_long'].items()) + ')'
    rows.append([n, d['files'], d['loc'], d['index_ms'], d['workspace_symbols']['count'],
                 cc.get('OK', 0), cc.get('SUSPECT_WRONG', 0), cc.get('CANDIDATE_MISS', 0), cc.get('AMBIGUOUS_SILENT', 0),
                 cc.get('EXTERNAL', 0), cc.get('DATA_CONTEXT_RESOLVED', 0),
                 '%d/%d/%d' % (oc.get('OK', 0), oc.get('CANDIDATE_MISS', 0), oc.get('AMBIGUOUS_SILENT', 0) + oc.get('SUSPECT_WRONG', 0)),
                 '%d/%d' % (dm_models, len(d['def_misses'])),
                 '%d/%d/%d' % (vc.get('VAR_OK', 0) + vc.get('VAR_UNBOUND_RESOLVED', 0), vc.get('CANDIDATE_VAR_MISS', 0), vc.get('VAR_SUSPECT_WRONG', 0)),
                 '%d/%d/%d' % (sum(d['error_responses'].values()), len(d['timeouts']), d['restarts']),
                 slow_s])
table(rows, ['repo', 'files', 'LOC', 'index ms', 'ws syms', 'call OK', 'call SUSPECT', 'call CAND_MISS', 'call AMBIG',
             'call EXT', 'call DATA_RES', 'obj OK/MISS/AMBIG', 'def-miss modeled/all', 'var OK/MISS/SUSPECT',
             'err/timeout/restart', 'slowest file'])

# ---------------------------------------------------------------- SUSPECT_WRONG
w('## SUSPECT_WRONG (top priority)')
w('')
sw = [(n, r) for n, d in R.items() for r in d['call_probes'] + d['obj_probes'] if r['class'] == 'SUSPECT_WRONG']
w('### Call / $obj probes: %d rows (by reason: %s)' % (len(sw), dict(Counter(r.get('reason') for _, r in sw))))
w('')
for n, r in sw[:100]:
    w('- `%s/%s:%d` **%s** [%s] `%s` -> %s' % (n, r['file'], r['line'], r['name'], r.get('reason'), r['text'][:110],
                                           '; '.join('%s:%s %s' % (t['file'], t['line'], t.get('fq') or t['text']) for t in r['targets'][:2])))
w('')
vs = [(n, r) for n, d in R.items() for r in d['var_probes'] if r['class'] == 'VAR_SUSPECT_WRONG']
byr = defaultdict(list)
for n, r in vs:
    byr[r.get('reason')].append((n, r))
w('### Variable probes: %d VAR_SUSPECT_WRONG rows' % len(vs))
w('')
rows = []
for reason, lst in byr.items():
    rows.append([reason, len(lst)] + [sum(1 for n, _ in lst if n == rp) for rp in R])
table(rows, ['reason', 'total'] + list(R))
ctx = Counter()
for n, r in vs:
    ctx['class-method' if 'in-class-method' in r['tags'] else 'plain-proc'] += 1
    for t in r['tags']:
        ctx['tag:' + t] += 1
w('Context of VAR_SUSPECT_WRONG uses: %s' % dict(ctx.most_common(12)))
w('')
for reason, lst in byr.items():
    w('#### %s (examples)' % reason)
    seen = Counter()
    for n, r in lst:
        if seen[n] >= 3 or sum(seen.values()) >= 15:
            continue
        seen[n] += 1
        w('- `%s/%s:%d` `$%s` in `%s` binding=%s `%s` -> %s' % (
            n, r['file'], r['line'], r['name'], r['proc'], r['binding_forms'], r['text'][:100],
            '; '.join('%s:%s(%s)' % (t['file'], t['line'], t.get('form')) for t in r.get('targets', [])[:3])))
    w('')

# ---------------------------------------------------------------- server false-positive symbols
w('### documentSymbol entries the oracle did not find (possible server false positives)')
w('')
rows = [[n, d['symbols_not_in_oracle']['count'], d['symbols_not_in_oracle'].get('by_where')] for n, d in R.items()]
table(rows, ['repo', 'count', 'where (oracle proc/method containing the symbol)'])
k = 0
for n, d in R.items():
    for s in d['symbols_not_in_oracle']['sample']:
        if s.get('where', '').startswith('inside') and k < 15:
            k += 1
            w('- `%s/%s:%d` %s (kind %s, under `%s`) [%s] `%s`' % (n, s['file'], s['line'], s['name'], s['kind'],
                                                             s['container'], s['where'], s['text'][:90]))
w('')

# ---------------------------------------------------------------- references
w('## F. References symmetry')
w('')
rows = []
for n, d in R.items():
    rs = d['refs_stats']
    rows.append([n, rs.get('defs_checked'), rs.get('refs_returned'), len(d['refs_missing']),
                 dict(Counter(x['why'] for x in d['refs_suspect'])), d['call_hierarchy']])
table(rows, ['repo', 'defs checked', 'refs returned', 'REFS_MISSING', 'REFS_SUSPECT by why', 'call hierarchy'])
for why in ('switch-pattern', 'text-mismatch', 'data-context', 'not-oracle-command-position'):
    lst = [(n, x) for n, d in R.items() for x in d['refs_suspect'] if x['why'] == why]
    if lst:
        w('REFS_SUSPECT `%s` (%d), examples:' % (why, len(lst)))
        for n, x in lst[:6]:
            w('- `%s/%s` ref of `%s` (def %s): `%s`' % (n, x['ref'], x['name'], x['def'], x['text'][:90]))
        w('')
lst = [(n, x) for n, d in R.items() for x in d['refs_missing']]
w('REFS_MISSING (%d) by call kind: %s' % (len(lst), dict(Counter(x['pk'] for _, x in lst))))
for n, x in lst[:8]:
    w('- `%s/%s` call of `%s` (def %s) missing from references: `%s`' % (n, x['call'], x['name'], x['def'], x['text'][:90]))
w('')

# ---------------------------------------------------------------- CANDIDATE_MISS calls
w('## C. Call-site CANDIDATE_MISS')
w('')
cm = [(n, r) for n, d in R.items() for r in d['call_probes'] if r['class'] == 'CANDIDATE_MISS']
w('Total %d (conf=script: %d, heuristic: %d, data: %d).' % (
    len(cm), sum(1 for _, r in cm if r['conf'] == 'script'), sum(1 for _, r in cm if r['conf'] == 'heuristic'),
    sum(1 for _, r in cm if r['conf'] == 'data')))
w('')
pk = Counter(r['pk'] for _, r in cm)
w('By position kind: %s' % dict(pk.most_common()))
w('')
tg = Counter()
for _, r in cm:
    for t in set(norm_tag(t) for t in r['tags'][1:]):
        tg[t] += 1
w('By context tag (a probe counts once per tag): %s' % dict(tg.most_common(25)))
w('')
reach = Counter('reachable' if r.get('n_reachable') else 'NOT-reachable-by-oracle-ns-rules' for _, r in cm)
w('Oracle reachability of the unique def: %s' % dict(reach))
w('')
w('By def form: %s' % dict(Counter(f for _, r in cm for f in r.get('def_forms', [])).most_common(10)))
w('')
per = Counter()
for _, r in cm:
    rel = 'relative-qualified' if any(t.startswith('relative-qualified') for t in r['tags']) else \
        'callback' if r['pk'].startswith('callback') else 'test-body' if 'inside-test-body' in r['tags'] else \
        'unknown-trailing/heuristic' if r['conf'] == 'heuristic' else 'other'
    per[rel] += 1
w('Coarse buckets: %s' % dict(per))
w('')
w('Examples (spread across buckets):')
seen = Counter()
for n, r in cm:
    b = 'relative' if any(t.startswith('relative-qualified') for t in r['tags']) else r['pk'].split(':')[0] + ('/test' if 'inside-test-body' in r['tags'] else '') + '/' + r['conf']
    if seen[b] >= 2 or sum(seen.values()) >= 18:
        continue
    seen[b] += 1
    w('- `%s/%s:%d` `%s` [%s; %s] ns=%s `%s` (def %s)' % (n, r['file'], r['line'], r['name'], r['pk'], ','.join(r['tags'][1:4]),
                                                       r['ns'], r['text'][:90], (r.get('defs') or [{}])[0].get('fq')))
w('')
am = [(n, r) for n, d in R.items() for r in d['call_probes'] if r['class'] == 'AMBIGUOUS_SILENT']
w('AMBIGUOUS_SILENT %d, of which exactly one def is reachable by oracle namespace rules (likely misses): %d.' % (
    len(am), sum(1 for _, r in am if r.get('n_reachable') == 1)))
w('')
other = Counter((n, r['class']) for n, d in R.items() for r in d['call_probes'] if r['class'] in ('OK_SILENT', 'DATA_CONTEXT_RESOLVED', 'TIMEOUT', 'ERROR', 'DEAD'))
w('Other classes: %s. DATA_CONTEXT_RESOLVED = resolved a "call" inside a brace the oracle considers data (mostly `subst {...}` script templates; informational).' % {'%s:%s' % k: v for k, v in other.items()})
w('')
w('Call probes capped: %s' % {n: d['call_probes_capped'] for n, d in R.items() if d['call_probes_capped']})
w('')

# ---------------------------------------------------------------- D obj
w('## D. `$obj method` / `$this` / `my` probes')
w('')
rows = [[n, d['oo_usage'], d.get('obj_usage'), d['obj_counts'], d['itcl_imported']] for n, d in R.items()]
table(rows, ['repo', 'OO definitions (itcl/snit/tcloo)', 'receiver kinds seen', 'probe classes', 'itcl::* imported'])
ob = [(n, r) for n, d in R.items() for r in d['obj_probes'] if r['class'] != 'OK']
w('Non-OK by receiver tag: %s' % dict(Counter((r['class'], r['tags'][0]) for _, r in ob).most_common(12)))
w('Typed receivers among misses: %d' % sum(1 for _, r in ob if any(t.startswith('typed-from') for t in r['tags'])))
w('')
seen = Counter()
for n, r in ob:
    if seen[(n, r['tags'][0])] >= 2 or sum(seen.values()) >= 12:
        continue
    seen[(n, r['tags'][0])] += 1
    w('- `%s/%s:%d` %s `%s` [%s] `%s`' % (n, r['file'], r['line'], r['class'], r['name'], ','.join(r['tags'][:3]), r['text'][:90]))
w('')

# ---------------------------------------------------------------- B defs
w('## B. Definition coverage (oracle vs documentSymbol)')
w('')
tot, miss = Counter(), Counter()
modeled = {}
for n, d in R.items():
    tot.update(d['def_forms_total'])
    miss.update(d['def_forms_missed'])
    for m in d['def_misses']:
        modeled[m['form']] = m['models']
rows = sorted(([f, tot[f], miss[f], 'yes' if modeled.get(f) else 'no'] for f in miss), key=lambda x: (x[3] != 'yes', -x[2]))
table(rows, ['form', 'oracle count', 'CANDIDATE_DEF_MISS', 'server claims to model'])
w('Forms with zero misses: %s' % {f: tot[f] for f in tot if f not in miss})
w('')
dm = [(n, m) for n, d in R.items() for m in d['def_misses']]
tg = Counter(t for _, m in dm if m['models'] for t in set(norm_tag(x) for x in m['tags']))
w('Modeled-form misses by context tag: %s' % dict(tg.most_common(15)))
w('')
seen = Counter()
for n, m in sorted(dm, key=lambda x: not x[1]['models']):
    if seen[m['form']] >= 2 or sum(seen.values()) >= 16:
        continue
    seen[m['form']] += 1
    w('- `%s/%s:%d` [%s%s] %s `%s` tags=%s' % (n, m['file'], m['line'], m['form'], '' if m['models'] else ', unmodeled',
                                           m['name'], m['text'][:90], [norm_tag(t) for t in m['tags']][-3:]))
w('')
w('Recurring definition-shaped heads (`HEAD name args {multi-line body}` at namespace level): %s' % {
    n: d['def_shaped_heads'] for n, d in R.items() if d['def_shaped_heads']})
w('')

# ---------------------------------------------------------------- E vars
w('## E. Variable probes')
w('')
rows = [[n] + [d['var_counts'].get(k, 0) for k in ('VAR_OK', 'CANDIDATE_VAR_MISS', 'VAR_SUSPECT_WRONG', 'VAR_UNBOUND_EMPTY', 'VAR_UNBOUND_RESOLVED')]
        + [d['var_probes_capped']] for n, d in R.items()]
table(rows, ['repo', 'VAR_OK', 'CANDIDATE_VAR_MISS', 'VAR_SUSPECT_WRONG', 'UNBOUND_EMPTY', 'UNBOUND_RESOLVED', 'capped'])
f, t = Counter(), Counter()
for d in R.values():
    f.update(d['var_miss_by_form'])
    t.update(d['var_miss_by_tag'])
w('CANDIDATE_VAR_MISS by binding form found in the proc body (a probe counts once per form): %s' % dict(f.most_common()))
w('')
w('CANDIDATE_VAR_MISS by use-site tag: %s' % dict(t.most_common()))
w('')
vm = [(n, r) for n, d in R.items() for r in d['var_probes'] if r['class'] == 'CANDIDATE_VAR_MISS']
only = Counter(tuple(r['binding_forms']) for _, r in vm if len(r['binding_forms']) == 1)
w('Misses whose ONLY binding form is X: %s' % {k[0]: v for k, v in only.most_common(15)})
w('')
seen = Counter()
for n, r in vm:
    key = (tuple(r['binding_forms'][:1]), tuple(r['tags'][:1]))
    if seen[key] >= 1 or sum(seen.values()) >= 15:
        continue
    seen[key] += 1
    w('- `%s/%s:%d` `$%s` in `%s` forms=%s tags=%s `%s`' % (n, r['file'], r['line'], r['name'], r['proc'], r['binding_forms'],
                                                         r['tags'], r['text'][:90]))
w('')

# ---------------------------------------------------------------- G
w('## G. Semantic-token consistency (call probes)')
w('')
sm = [(n, r) for n, d in R.items() for r in d['call_probes'] if r.get('sem_mismatch')]
w('Mismatches: %d; by type: %s; by repo: %s' % (len(sm), dict(Counter(r['sem_mismatch'] for _, r in sm)),
                                              dict(Counter(n for n, _ in sm))))
w('')
for n, r in sm[:: max(1, len(sm) // 10)][:10]:
    w('- `%s/%s:%d` `%s` %s (class %s, tags %s) `%s`' % (n, r['file'], r['line'], r['name'], r['sem_mismatch'], r['class'],
                                                       r['tags'][:3], r['text'][:80]))
w('')

# ---------------------------------------------------------------- A perf
w('## A. Robustness and performance')
w('')
lat = defaultdict(lambda: [0, 0, 0, 0])
for d in R.values():
    for m, s in d['latency'].items():
        a = lat[m]
        a[0] += s['n']
        a[1] = max(a[1], s['p50'] or 0)
        a[2] = max(a[2], s['p95'] or 0)
        a[3] = max(a[3], s['max'])
table([[m] + v for m, v in sorted(lat.items())], ['method', 'requests', 'worst repo p50 ms', 'worst repo p95 ms', 'max ms'])
w('Timeouts (10 s) / dead server: %s' % {n: [t['method'] for t in d['timeouts']] for n, d in R.items() if d['timeouts']})
w('')
w('Files flagged (slow >250 ms or non-ok) : %s' % {n: [(f['file'], f['slow'], f.get('retry_long')) for f in d['files_flagged']] for n, d in R.items() if d['files_flagged']})
w('')
w('Slowest files: %s' % {n: d['slowest_files'][:2] for n, d in R.items()})
w('')
w('Stderr flagged lines: %s' % {n: (d['stderr_flagged_count'], d['stderr_flagged'][:3]) for n, d in R.items()})
w('')
w('Error responses: %s. Server->client requests seen: %s' % ({n: d['error_responses'] for n, d in R.items() if d['error_responses']},
                                                           {n: d['server_requests_seen'] for n, d in list(R.items())[:1]}))
w('')

# ---------------------------------------------------------------- H
w('## H. Files the workspace index skips')
w('')
rows = [[n, len(d['skipped_files']), dict(Counter(s['why'] for s in d['skipped_files'])),
         ', '.join(s['file'] for s in d['skipped_files'] if s['why'] == 'shebang-no-ext')[:120]] for n, d in R.items()]
table(rows, ['repo', 'skipped', 'by reason', 'extensionless tcl scripts'])
for n, d in R.items():
    for e in d.get('test_file_experiment', []):
        w('- **%s/%s**: refs from test before open %s; after didOpen goto-def probes %s; refs after open %s. Sample: %s' % (
            n, e['test_file'], sum(e['refs_from_test_before_open'].values()), e['probes_after_open'],
            sum(e['refs_from_test_after_open'].values()),
            '; '.join('L%d `%s` %s/%s' % (s['line'], s['name'], s['class'], s.get('where')) for s in e['probe_samples'][:3])))
w('')
open(os.path.join(RES, 'SUMMARY.md'), 'w').write('\n'.join(L) + '\n')
print('wrote SUMMARY.md: %d lines' % len(L))
